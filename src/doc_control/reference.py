"""Generated reference documents: every operation with its schema, every error code.

``python -m doc_control.reference`` rewrites ``docs/operations.md`` and
``docs/errors.md`` from the registry and :mod:`doc_control.errors`; a test checks the
committed files are current, so the reference never drifts from the code.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from doc_control.errors import HINTS, ErrorCode
from doc_control.registry import ALIASES, REGISTRY, load_operations

HEADER = "<!-- Generated by `python -m doc_control.reference`; do not edit by hand. -->\n\n"


def _properties(schema: dict[str, Any]) -> list[str]:
    props: dict[str, Any] = schema.get("properties", {})
    required = set(schema.get("required", []))
    rows = []
    for name, spec in props.items():
        options = spec.get("anyOf") or spec.get("oneOf") or []
        kind = spec.get("type") or " \\| ".join(
            str(o.get("type", "?")) for o in options if isinstance(o, dict)
        )
        if isinstance(kind, list):
            kind = " \\| ".join(kind)
        kind = kind or "any"
        if "enum" in spec:
            kind = " \\| ".join(f"`{v}`" for v in spec["enum"])
        text = " ".join(str(spec.get("description", "")).split()).replace("|", "\\|")
        need = "yes" if name in required else ""
        rows.append(f"| `{name}` | {kind} | {need} | {text} |")
    return rows


def operations_markdown() -> str:
    """Every registered operation and every batch kind, with its request fields."""
    load_operations()
    from doc_control.ops.batch import ALL_SCHEMAS

    out = [HEADER, "# Operation reference\n"]
    out.append(
        "Every operation takes a JSON request (`doc-control <op> --json '{…}'`, the MCP "
        "tool of the same name with `.` as `_`, or `doc_control.api`) and answers with the "
        "envelope `{api, ok, op, doc, result, warnings, next}` or an error from "
        "[errors.md](errors.md). Returns lists the keys of `result` (Always: present in every "
        "success). `doc-control server.help <op>` prints the full JSON Schemas of the request "
        "and the result; MCP lists the result's as the tool's `outputSchema`.\n"
    )
    for name in sorted(REGISTRY):
        op = REGISTRY[name]
        out.append(f"## `{name}` ({op.kind})\n\n{' '.join(op.summary.split())}\n")
        rows = _properties(op.schema)
        if rows:
            out.append("| Field | Type | Required | Meaning |\n|---|---|---|---|")
            out.extend(rows)
            out.append("")
        returns = _properties(op.output or {})
        if returns:
            out.append("Returns (`result`):\n")
            out.append("| Key | Type | Always | Meaning |\n|---|---|---|---|")
            out.extend(returns)
            out.append("")
    out.append("# Batch operation kinds\n")
    out.append("The kinds `doc.batch` takes in `ops`, each applied as a tracked change.\n")
    for name in sorted(ALL_SCHEMAS):
        schema = ALL_SCHEMAS[name]
        summary = " ".join(str(schema.get("description", "")).split())
        out.append(f"## `{name}`\n" + (f"\n{summary}\n" if summary else ""))
        rows = _properties(schema)
        if rows:
            out.append("| Field | Type | Required | Meaning |\n|---|---|---|---|")
            out.extend(rows)
            out.append("")
    out.append("# Renamed operations\n")
    out.append(
        "0.7.0 named every operation `resource.action`, with a singular resource. The old "
        "names still run (CLI, `server.help`, `doc_control.api`, MCP `tools/call`) but are "
        "no longer listed.\n"
    )
    out.append("| Old name | Current name |\n|---|---|")
    out.extend(f"| `{old}` | `{new}` |" for old, new in sorted(ALIASES.items()))
    return "\n".join(out).rstrip() + "\n"


def errors_markdown() -> str:
    """Every error code with its hint."""
    out = [HEADER, "# Error reference\n"]
    out.append(
        "An error answers with `ok: false` and `error: {code, message, hint, details}`. "
        "The CLI exits 2 for a request problem and 1 otherwise.\n"
    )
    out.append("| Code | What to do |\n|---|---|")
    out.extend(f"| `{code.value}` | {HINTS[code]} |" for code in ErrorCode)
    return "\n".join(out) + "\n"


def write(root: Path) -> list[Path]:
    docs = root / "docs"
    docs.mkdir(exist_ok=True)
    targets = {docs / "operations.md": operations_markdown(), docs / "errors.md": errors_markdown()}
    for path, text in targets.items():
        path.write_text(text, encoding="utf-8")
    return list(targets)


if __name__ == "__main__":
    for written in write(Path(sys.argv[1]) if len(sys.argv) > 1 else Path.cwd()):
        print(written)
